function mac = tableRegimes(T, resDir)
% S2: how each battery-limited method monitors between charges, per setup (means over the seeds):
% J_T, visits and dwells per agent, the mean dwell, the D2 dwell time per agent (EA), the SOC at
% plug-in and the charges per agent
S = T(T.Study == "S2", :);
mac = strings(0, 1);
if isempty(S) || ~any(~isnan(S.DwellMean)), return; end
methods = ["EA-SO", "EA-FO-0", "BA-SO", "BA"]; heads = ["EA (SO)", "EA (FO-0)", "BA (SO)", "BA (FO-0)"];
fid = fopen(fullfile(resDir, 'tab_regimes.tex'), 'w');
fprintf(fid, '%% generated by energyExperiments("collect"): S2 means over the seeds, per agent where stated\n');
fprintf(fid, '\\begin{tabular}{|l|l|c|c|c|c|c|c|}\n\\hline\n');
fprintf(fid, 'Setup & Method & $J_T$ & Visits & Dwell (s) & D2 (s) & SOC at plug-in (\\%%) & Charges \\\\ \\hline\n');
for sc = unique(S.Scenario, 'stable')'
    first = true;
    for k = 1:numel(methods)
        m = S.Scenario == sc & S.Method == methods(k);
        if ~any(m), continue; end
        n = S.Agents(m);
        J = mean(S.J(m)); vis = mean(S.Visits(m) ./ n); dw = mean(S.DwellMean(m), 'omitnan');
        d2 = mean(S.D2Time(m) ./ n, 'omitnan'); soc = 100 * mean(S.SocIn(m), 'omitnan'); ch = mean(S.Charges(m) ./ n);
        d2txt = sprintf('%.0f', d2); if isnan(d2), d2txt = "--"; end
        name = ""; if first, name = setupName(sc); first = false; end
        fprintf(fid, '%s & %s & %.0f & %.1f & %.1f & %s & %.0f & %.1f \\\\\n', name, heads(k), J, vis, dw, d2txt, soc, ch);
        key = camel(methods(k)) + camel(sc);
        mac(end+1, 1) = macro("VisitsPerAgent" + key, vis, '%.0f'); %#ok<AGROW>
        mac(end+1, 1) = macro("DwellMean" + key, dw, '%.1f'); %#ok<AGROW>
        mac(end+1, 1) = macro("SocIn" + key, soc, '%.0f'); %#ok<AGROW>
        if ~isnan(d2), mac(end+1, 1) = macro("DTwoTime" + key, d2, '%.0f'); end %#ok<AGROW>
    end
    fprintf(fid, '\\hline\n');
end
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
end

function mac = ablationTable(file, rows, setups, first, key, extra)
% rows: {label, runs, tag}; one column of mean J_T per setup over the seeds of each row's runs
% (with extra: the docks' busy share and messages per RHCP too)
if nargin < 6, extra = false; end
mac = strings(0, 1);
fid = fopen(file, 'w');
fprintf(fid, '%% generated by energyExperiments("collect"): mean J_T over the seeds run (S2''s reference: seeds 1-5, or 1-10 in S3); bold: the lowest per setup\n');
nc = numel(setups) * (1 + 2 * extra);
fprintf(fid, '\\begin{tabular}{|l|%s}\n\\hline\n', repmat('c|', 1, nc));
heads = arrayfun(@setupName, setups);
if extra
    heads = arrayfun(@(h) h + " & busy (\%) & msg./RHCP", heads);
end
fprintf(fid, '%s & %s \\\\ \\hline\n', first, strjoin(heads, ' & '));
Jm = inf(size(rows, 1), numel(setups));   % mean J per row and setup (bold: the lowest per setup)
for q = 1:size(rows, 1)
    R = rows{q, 2};
    if isempty(R), continue; end
    for s = 1:numel(setups)
        J = stat(R, R.Scenario == setups(s), 'J');
        if ~isnan(J), Jm(q, s) = J; end
    end
end
[~, best] = min(Jm, [], 1);
for q = 1:size(rows, 1)
    R = rows{q, 2};
    if isempty(R), continue; end
    cells = strings(0);
    for sc = setups'
        m = R.Scenario == sc;
        J = stat(R, m, 'J');
        Jtxt = sprintf('%.0f', J); if best(setups == sc) == q, Jtxt = "\textbf{" + Jtxt + "}"; end
        cells(end+1) = Jtxt; %#ok<AGROW>
        if extra
            cells(end+1) = sprintf('%.0f', 100 * stat(R, m, 'Busy')); %#ok<AGROW>
            cells(end+1) = sprintf('%.3f', mean(R.Messages(m) ./ R.RHCPs(m), 'omitnan')); %#ok<AGROW>
        end
        lbl = regexprep(replace(rows{q, 1}, ["0.5", "1", "2", "5"], [" Half ", " One ", " Two ", " Five "]), '[^A-Za-z ]', '');
        mac(end+1, 1) = macro(key + "J" + camel(lbl) + camel(sc), J, '%.0f'); %#ok<AGROW>
    end
    fprintf(fid, '%s & %s \\\\ \\hline\n', rows{q, 1}, strjoin(cells, ' & '));
end
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
end

