function T = energyCollect(L, runDir, resDir, quick)
% The results of energyExperiments' saved runs: runs.csv (one row per run), the LaTeX tables of
% Sec. VII (complete tabular environments), energy_macros.tex (every number the text quotes; full
% mode only) and the figures of S2, S6, S8 and S9 (PDF and 300-dpi PNG)
rows = {};
for id = 1:height(L)
    f = fullfile(runDir, sprintf('%04d.mat', id));
    if ~isfile(f), continue; end
    r = load(f, 'r').r; mv = r.metrics; st = r.stats;
    rows(end+1, :) = {id, L.Study(id), L.Scenario(id), L.Method(id), L.Seed(id), L.Variant(id), r.J, ...
        mfield(mv, 'EnergyUsed'), mfield(mv, 'MinimumSOC'), mfield(mv, 'Charges'), mfield(mv, 'MeanWait'), ...
        mfield(mv, 'MonitoringShare'), mfield(mv, 'LargestGap'), sfield(st, 'messages'), sfield(st, 'relays'), ...
        sfield(st, 'rhcp'), sfield(st, 'bookingChanges'), r.busy, r.trueMinSoc, r.violations, r.delays, ...
        r.socErrMax, r.seconds}; %#ok<AGROW>
end
T = cell2table(rows, 'VariableNames', {'Id', 'Study', 'Scenario', 'Method', 'Seed', 'Variant', 'J', ...
    'Energy', 'MinSoc', 'Charges', 'Wait', 'Share', 'Gap', 'Messages', 'Relays', 'RHCPs', 'Changes', ...
    'Busy', 'TrueMinSoc', 'Violations', 'Delays', 'SocErrMax', 'Seconds'});
writetable(T, fullfile(resDir, 'runs.csv'));
mac = strings(0, 1);
mac = [mac; tableMain(T, resDir)];
mac = [mac; tableAblations(T, resDir)];
mac = [mac; stationsFigure(L, runDir, resDir)];
mac = [mac; physicalResults(L, T, runDir, resDir)];
mac = [mac; stoppingResults(L, runDir, resDir)];
mainFigure(L, runDir, resDir);
if ~quick
    writelines(["% generated by energyExperiments(""collect""): numbers quoted in Sec. VII"; mac(:)], ...
        fullfile(resDir, 'energy_macros.tex'));
end
end

function v = mfield(s, f)
if isstruct(s) && isfield(s, f), v = s.(f); else, v = NaN; end
end

function v = sfield(s, f)
v = NaN;
if isstruct(s) && isfield(s, f) && isscalar(s.(f)), v = s.(f); end
end

% ------------------------------------------------------------------------------------------
function m = macro(name, val, fmt)
m = "\newcommand{\er" + name + "}{" + sprintf(fmt, val) + "}";
end

function n = camel(s)
% A macro-safe CamelCase name (letters only)
s = replace(string(s), ["FO-3", "FO-0", "-bat", "Energy_", "_1Dock", "_2Docks", "_2Stations", "-", "_", " "], ...
    ["FoThree", "FoZero", "Bat", "", "One", "Two", "", " ", " ", " "]);
w = split(lower(s));
w = w(w ~= "");
n = strjoin(upper(extractBefore(w, 2)) + extractAfter(w, 1), "");
n = regexprep(n, '[^A-Za-z]', '');
end

function [mu, lo, hi, n] = stat(T, mask, col)
x = T.(col)(mask); x = x(~isnan(x));
n = numel(x); mu = mean(x); lo = min(x); hi = max(x);
if isempty(x), mu = NaN; lo = NaN; hi = NaN; end
end

