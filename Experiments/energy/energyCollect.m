function mac = setupMacros()
% The setups' numbers quoted in Sec. VII: targets (stations not counted), agents, stations and
% docks, the map (the 100 m x 100 m canvas; for the office also the building's walls), the robots'
% P_I and P_M (with and without the battery's loss beta P^2), capacity, reserve, station power
% and the slot t_s = (Q - E_min)/(P_c - P_I) with the losses (ChargingStation.slotLength)
root = fileparts(which('MainUI'));
mac = strings(0, 1);
for f = ["Energy_Office_1Dock", "Energy_Campus_2Stations"]
    s = load(fullfile(root, 'Configurations', 'Energy', f + ".mat"), 's').s;
    model = ScenarioModel(DijkstraCornerPlanner()); model.importLayout(s);
    st = model.targets(arrayfun(@(t) isa(t, 'ChargingStation'), model.targets));
    key = replace(f, ["Energy_Office_1Dock", "Energy_Campus_2Stations"], ["Office", "Campus"]);
    mac(end+1, 1) = macro(key + "Targets", numel(model.targets) - numel(st), '%d');
    mac(end+1, 1) = macro(key + "Agents", numel(model.agents), '%d');
    mac(end+1, 1) = macro(key + "Stations", numel(st), '%d');
    mac(end+1, 1) = macro(key + "Docks", st(1).docks, '%d');
    mac(end+1, 1) = macro(key + "Width", 100, '%d');
    mac(end+1, 1) = macro(key + "Height", 100, '%d');
    if key == "Office"
        W = s.walls;
        mac(end+1, 1) = macro("OfficeBuildingWidth", max([W(:, 1); W(:, 3)]) - min([W(:, 1); W(:, 3)]), '%.0f');
        mac(end+1, 1) = macro("OfficeBuildingHeight", max([W(:, 2); W(:, 4)]) - min([W(:, 2); W(:, 4)]), '%.0f');
        a = model.agents(1); b = a.battery;
        mac(end+1, 1) = macro("PI", b.idlePower(), '%.1f');
        mac(end+1, 1) = macro("PILoss", b.idleDraw(), '%.2f');
        mac(end+1, 1) = macro("PM", b.movePower(), '%.1f');
        mac(end+1, 1) = macro("CapacityWh", b.capacityWh, '%g');
        mac(end+1, 1) = macro("CapacityKJ", b.capacity / 1000, '%.1f');
        mac(end+1, 1) = macro("SocMinPct", 10, '%d');
        mac(end+1, 1) = macro("StationPower", st(1).chargePower, '%g');
        mac(end+1, 1) = macro("SlotLength", st(1).slotLength(a, 0.1), '%.0f');
        mac(end+1, 1) = macro("RobotSpeed", a.state.maxSpeed, '%g');
        mac(end+1, 1) = macro("RobotAccel", a.state.maxAccel, '%g');
        mac(end+1, 1) = macro("BatteryRZero", b.R0, '%g');
        mac(end+1, 1) = macro("BatteryVoc", b.Voc, '%g');
    end
end
end

function mac = profileMacros()
% S1's numbers (Sec. VII-B), as in fig_profiles: y = 20 m, (c1, c2) = (17.75, 1.16), no limits.
% The excess of the cubic (the c2 = 0 optimum) and of FO-3 over the SO loss at rho = 10 and 40 s
% (%), FO-3's tau*/rho there, the transit time rho_E minimizing Delta P rho + L_SO(rho) with
% Delta P = P_M - P_I (the robots' powers without battery losses), y/rho_E, and sqrt(Delta P/c2)
c1 = 17.75; c2 = 1.16; nu = sqrt(c2 / c1); y = 20;
b = Battery(CapacityWh=9); dP = b.movePower() - b.idlePower();
Lso = @(r) SpeedProfile.loss("SO", y, r, Inf, Inf, c1, c2);
mac = strings(0, 1);
for r = [10 40]
    tag = "Ten"; if r == 40, tag = "Forty"; end
    [Eu, Ev] = SpeedProfile.integrals(SpeedProfile.shape("SO", y, r));
    mac(end+1, 1) = macro("ProfCubGap" + tag, 100 * ((c1 * Eu + c2 * Ev) / Lso(r) - 1), '%.1f');
    mac(end+1, 1) = macro("ProfFoThreeGap" + tag, 100 * (SpeedProfile.loss("FO-3", y, r, Inf, Inf, c1, c2) / Lso(r) - 1), '%.1f');
    P = SpeedProfile.shape("FO-3", y, r, Inf, Inf, nu);
    mac(end+1, 1) = macro("ProfTau" + tag, P.s / r, '%.3f');
end
rhoE = fminbnd(@(r) dP * r + Lso(r), 1, 500, optimset('TolX', 1e-8));
mac(end+1, 1) = macro("ProfRhoE", rhoE, '%.1f');
mac(end+1, 1) = macro("ProfSpeedE", y / rhoE, '%.2f');
mac(end+1, 1) = macro("ProfSpeedLimitE", sqrt(dP / c2), '%.2f');
end

function mac = tableMain(T, resDir)
% S2: per setup and method, J_T mean [min, max] over the seeds, energy, lowest SOC, charges, mean
% wait, monitoring share and messages per RHCP; the macros give the means
S = T(T.Study == "S2", :);
mac = strings(0, 1);
if isempty(S), return; end
methods = ["EA-SO", "EA-FO-3", "EA-FO-0", "BA-SO", "BA", "ED-RHC", "ED-RHC-alpha", "ED-ORHC-SO", "ED-ORHC-SO-bat", ...
    "ED-ORHC-FO-3", "ED-ORHC-FO-3-bat"];
heads = ["EA (SO)", "EA (FO-3)", "EA (FO-0)", "BA (SO)", "BA (FO-0)", "ED-RHC$^\ast$", "ED-RHC-$\alpha^\ast$", ...
    "ED-ORHC-SO$^\ast$", "ED-ORHC-SO", "ED-ORHC-FO-3$^\ast$", "ED-ORHC-FO-3"];
setups = unique(S.Scenario, 'stable');
fid = fopen(fullfile(resDir, 'tab_main.tex'), 'w');
fprintf(fid, '%% generated by energyExperiments("collect"); $^\\ast$: unlimited batteries; bold: lowest J_T of the battery-limited methods\n');
fprintf(fid, '\\begin{tabular}{|l|l|c|c|c|c|c|c|}\n\\hline\n');
fprintf(fid, 'Setup & Method & $J_T$ & $E$ (kJ) & SOC$_{\\min}$ (\\%%) & Charges & Wait (s) & Monitor (\\%%) \\\\ \\hline\n');
limited = ~contains(heads, "ast");   % methods with a battery limit (the bold candidates)
for sc = setups'
    first = true;
    Jall = inf(1, numel(methods));
    for k = find(limited)
        mask = S.Scenario == sc & S.Method == methods(k);
        if any(mask), Jall(k) = stat(S, mask, 'J'); end
    end
    [~, best] = min(Jall);
    for k = 1:numel(methods)
        mask = S.Scenario == sc & S.Method == methods(k);
        if ~any(mask), continue; end
        [J, lo, hi] = stat(S, mask, 'J');
        E = stat(S, mask, 'Energy'); soc = stat(S, mask, 'MinSoc'); ch = stat(S, mask, 'Charges');
        wt = stat(S, mask, 'Wait'); sh = stat(S, mask, 'Share');
        name = ""; if first, name = setupName(sc); first = false; end
        unlimited = contains(heads(k), "ast");   % SOC and charges mean nothing without a battery limit
        socTxt = sprintf('%.0f', max(soc, 0)); chTxt = sprintf('%.1f', ch);
        if unlimited, socTxt = "--"; chTxt = "--"; end
        Jtxt = sprintf('%.0f', J); if k == best, Jtxt = "\textbf{" + Jtxt + "}"; end
        fprintf(fid, '%s & %s & %s [%.0f, %.0f] & %.0f & %s & %s & %.0f & %.0f \\\\\n', name, heads(k), ...
            Jtxt, lo, hi, E, socTxt, chTxt, wt, sh);
        mac(end+1, 1) = macro("J" + camel(methods(k)) + camel(sc), J, '%.0f'); %#ok<AGROW>
        mac(end+1, 1) = macro("Share" + camel(methods(k)) + camel(sc), sh, '%.0f'); %#ok<AGROW>
        mac(end+1, 1) = macro("Energy" + camel(methods(k)) + camel(sc), E, '%.0f'); %#ok<AGROW>
        if ~contains(heads(k), "ast")
            mac(end+1, 1) = macro("MinSoc" + camel(methods(k)) + camel(sc), max(soc, 0), '%.0f'); %#ok<AGROW>
        end
    end
    fprintf(fid, '\\hline\n');
end
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
end

