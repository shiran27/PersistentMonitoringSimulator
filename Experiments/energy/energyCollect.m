function mac = stoppingResults(L, runDir, resDir)
% S9: J at the stop, against kappa, for the K-weighted method and ED-ORHC-SO, stopped at T, at the
% energy the kappa = 0 run uses in T/2, and at its visits in T/2 (per seed); the stop's time,
% energy and visits in tab_stopping.tex
mac = strings(0, 1);
idx = find(L.Study == "S9");
R = {};
for id = idx'
    f = fullfile(runDir, sprintf('%04d.mat', id));
    if isfile(f), R{end+1} = load(f, 'r').r; end %#ok<AGROW>
end
if isempty(R), return; end
R = [R{:}];
seeds = unique([R.seed]);
kap = @(r) str2double(extractAfter(r.variant, "kappa "));
crit = ["time", "energy", "visits"];
res = struct('method', {}, 'kappa', {}, 'crit', {}, 'J', {}, 't', {}, 'E', {}, 'V', {});
for s = seeds
    pilot = R([R.seed] == s & [R.method] == "K-weighted" & arrayfun(@(r) kap(r) == 0, R));
    if isempty(pilot), continue; end
    half = find(pilot.t >= pilot.t(end) / 2, 1);
    Estop = pilot.energy(half); Vstop = pilot.visits(half);
    for r = R([R.seed] == s)
        for c = crit
            switch c
                case "time",   k = numel(r.t);
                case "energy", k = find(r.energy >= Estop, 1); if isempty(k), k = numel(r.t); end
                case "visits", k = find(r.visits >= Vstop, 1); if isempty(k), k = numel(r.t); end
            end
            kk = 0; if r.method == "K-weighted", kk = kap(r); end
            res(end+1) = struct('method', r.method, 'kappa', kk, 'crit', c, 'J', r.Jt(k), 't', r.t(k), ...
                'E', r.energy(k) / 1000, 'V', r.visits(k)); %#ok<AGROW>
        end
    end
end
if isempty(res), return; end
f = figure('Visible', 'off', 'Units', 'inches', 'Position', [0 0 7.16 2.1]);
tiledlayout(1, 3, 'TileSpacing', 'compact', 'Padding', 'compact');
titles = ["fixed time $T$", "fixed energy", "fixed visits"];
fid = fopen(fullfile(resDir, 'tab_stopping.tex'), 'w');
fprintf(fid, '%% generated by energyExperiments("collect"): means over the seeds\n');
fprintf(fid, '\\begin{tabular}{|l|l|c|c|c|c|}\n\\hline\nStop & Method & $J$ & $t$ (s) & $E$ (kJ) & Visits \\\\ \\hline\n');
for q = 1:3
    nexttile; hold on; grid on; box on;
    c = res([res.crit] == crit(q));
    K = c([c.method] == "K-weighted"); ks = unique([K.kappa]);
    Jk = arrayfun(@(k) mean([K([K.kappa] == k).J]), ks);
    plot(ks, Jk, 'o-', 'Color', [0 0.45 0.74], 'LineWidth', 1.1, 'MarkerSize', 3, 'DisplayName', '$K$-weighted');
    O = c([c.method] == "ED-ORHC-SO");
    if ~isempty(O), yline(mean([O.J]), '--', 'Color', [0.93 0.69 0.13], 'LineWidth', 1.1, 'DisplayName', 'ED-ORHC-SO'); end
    xlabel('$\kappa$', 'Interpreter', 'latex'); ylabel('$J$ at the stop', 'Interpreter', 'latex');
    title(titles(q), 'Interpreter', 'latex', 'FontWeight', 'normal');
    set(gca, 'FontSize', 8, 'TickLabelInterpreter', 'latex');
    if q == 1, legend('Interpreter', 'latex', 'Location', 'best', 'FontSize', 7); end
    for k = ks
        g = K([K.kappa] == k);
        fprintf(fid, '%s & $K$-weighted, $\\kappa = %g$ & %.0f & %.0f & %.1f & %.0f \\\\\n', crit(q), k, mean([g.J]), ...
            mean([g.t]), mean([g.E]), mean([g.V]));
    end
    if ~isempty(O)
        fprintf(fid, '%s & ED-ORHC-SO & %.0f & %.0f & %.1f & %.0f \\\\ \\hline\n', crit(q), mean([O.J]), mean([O.t]), ...
            mean([O.E]), mean([O.V]));
        mac(end+1, 1) = macro("StopJOrhc" + camel(crit(q)), mean([O.J]), '%.0f'); %#ok<AGROW>
    end
    [Jbest, kb] = min(Jk);
    mac(end+1, 1) = macro("StopBestKappa" + camel(crit(q)), ks(kb), '%g'); %#ok<AGROW>
    mac(end+1, 1) = macro("StopBestJ" + camel(crit(q)), Jbest, '%.0f'); %#ok<AGROW>
end
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
saveFig(f, fullfile(resDir, 'fig_stopping'));
end

