function mac = tableAblations(T, resDir)
% S3 (objective forms), S4 (terminal values), S5 (booking strategies, with the docks' busy share
% and messages per RHCP) and S7 (charging methods): mean J_T per setup over seeds 1-5; the
% reference rows (dinkelbach, alpha, the S2 strategy) are S2's EA-SO runs of the same seeds
