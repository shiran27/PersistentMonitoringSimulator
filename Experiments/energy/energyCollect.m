function f = mvaShare(n, m, Z, S)
% Monitoring share of n agents with think time Z (monitoring per cycle) at a station of m servers
% with service time S, by exact mean value analysis of the closed network (load-dependent
% station: marginal queue-length probabilities)
p = zeros(1, n + 1); p(1) = 1;   % P(j at the station | population)
X = 0;
for k = 1:n
    R = 0; pn = zeros(1, k + 1);
    for j = 1:k
        R = R + j * S / min(j, m) * p(j);
    end
    X = k / (Z + R);
    for j = 1:k
        pn(j + 1) = X * S / min(j, m) * p(j);
    end
    pn(1) = 1 - sum(pn(2:end));
    p = pn;
end
f = X * Z / n;
end

