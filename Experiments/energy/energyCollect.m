setups = ["Energy_Office_1Dock", "Energy_Campus_2Stations"];
methods = ["EA-SO", "EA-FO-0", "BA", "ED-RHC", "ED-ORHC-SO-bat"];
labels = ["EA (SO)", "EA (FO-0)", "BA (FO-0)", "ED-RHC$^\ast$", "ED-ORHC-SO"];
f = figure('Visible', 'off', 'Units', 'inches', 'Position', [0 0 7.16 3.6]);
tiledlayout(2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');
any1 = false;
for row = 1:2
    for c = 1:2
        nexttile; hold on; grid on; box on;
        for k = 1:numel(methods)
            id = find(L.Study == "S2" & L.Scenario == setups(c) & L.Method == methods(k) & L.Seed == 1, 1);
            fl = fullfile(runDir, sprintf('%04d.mat', id));
            if isempty(id) || ~isfile(fl), continue; end
            r = load(fl, 'r').r; any1 = true;
            col = energyColors(replace(methods(k), "-bat", ""));
            if row == 1
                plot(r.t, r.Jt, 'LineWidth', 1.1, 'Color', col, 'DisplayName', labels(k));
            else
                plot(r.t, 100 * min(r.soc, [], 2), 'LineWidth', 1.1, 'Color', col, 'DisplayName', labels(k));
            end
        end
        if row == 1
            title(setupName(setups(c)), 'Interpreter', 'latex', 'FontWeight', 'normal');
            ylabel('$J(t)$', 'Interpreter', 'latex');
        else
            ylabel('lowest SOC (\%)', 'Interpreter', 'latex'); xlabel('$t$ [s]', 'Interpreter', 'latex');
            yline(10, 'k:', 'HandleVisibility', 'off');
        end
        set(gca, 'FontSize', 8, 'TickLabelInterpreter', 'latex');
        if row == 1 && c == 2, legend('Interpreter', 'latex', 'Location', 'northwest', 'FontSize', 7); end
    end
end
if any1, saveFig(f, fullfile(resDir, 'fig_main')); else, close(f); end
end

function saveFig(f, base)
exportgraphics(f, base + ".pdf", 'ContentType', 'vector');
exportgraphics(f, base + ".png", 'Resolution', 300);
close(f);
end
