rowsS3 = {"dinkelbach", ref, ""; "ratio", T(T.Study == "S3" & T.Method == "ratio", :), ""};
for f = ["x0.5", "x1", "x2"]
    rowsS3(end+1, :) = {"$\alpha_H$ " + replace(f, "x", "$\times$"), T(T.Study == "S3" & T.Method == "alphaH" & T.Variant == f, :), f}; %#ok<AGROW>
end
mac = [mac; ablationTable(fullfile(resDir, 'tab_forms.tex'), rowsS3, setups, "Form", "Forms")];
% S4
rowsS4 = {"$\alpha$ weights", ref, ""; "$\hat h_k$", T(T.Study == "S4" & T.Method == "hhat", :), ""; ...
    "none", T(T.Study == "S4" & T.Method == "none", :), ""};
mac = [mac; ablationTable(fullfile(resDir, 'tab_terminal.tex'), rowsS4, setups, "Terminal", "Terminal")];
% S5
S5 = T(T.Study == "S5", :);
rowsS5 = {"S2's strategy", ref, ""};
for k = ["R", "a", "b", "e"]
    m = S5(S5.Method == k & S5.Variant == "", :);
    if ~isempty(m), rowsS5(end+1, :) = {"(" + k + ")", m, ""}; end %#ok<AGROW>
end
for d = ["deadband", "deadband, delta 1", "deadband, delta 5"]
    m = S5(S5.Method == "R" & S5.Variant == d, :);
    lbl = "(R), deadband";
    if contains(d, "delta"), lbl = lbl + ", $\delta = " + extractAfter(d, "delta ") + "$ s"; end
    if ~isempty(m), rowsS5(end+1, :) = {lbl, m, ""}; end %#ok<AGROW>
end
mac = [mac; ablationTable(fullfile(resDir, 'tab_booking.tex'), rowsS5, setups, "Strategy", "Booking", true)];
% S7
S7 = T(T.Study == "S7", :);
rowsS7 = {};
for v = ["constant power", "CC-CV", "CC-CV tail", "swap"]
    m = S7(S7.Method == v, :);
    if ~isempty(m), rowsS7(end+1, :) = {v, m, ""}; end %#ok<AGROW>
end
if ~isempty(rowsS7)
    mac = [mac; ablationTable(fullfile(resDir, 'tab_charging.tex'), rowsS7, unique(S7.Scenario, 'stable'), "Charging", "Charging")];
end
end

function mac = ablationTable(file, rows, setups, first, key, extra)
% rows: {label, runs, tag}; one column of mean J_T per setup (with extra: the docks' busy share
% and messages per RHCP too)
if nargin < 6, extra = false; end
mac = strings(0, 1);
fid = fopen(file, 'w');
fprintf(fid, '%% generated by energyExperiments("collect"): mean J_T over seeds 1-5\n');
nc = numel(setups) * (1 + 2 * extra);
fprintf(fid, '\\begin{tabular}{|l|%s}\n\\hline\n', repmat('c|', 1, nc));
heads = arrayfun(@setupName, setups);
if extra
    heads = arrayfun(@(h) h + " & busy (\%) & msg./RHCP", heads);
end
fprintf(fid, '%s & %s \\\\ \\hline\n', first, strjoin(heads, ' & '));
for q = 1:size(rows, 1)
    R = rows{q, 2};
    if isempty(R), continue; end
    cells = strings(0);
    for sc = setups'
        m = R.Scenario == sc & R.Seed <= 5;
        J = stat(R, m, 'J');
        cells(end+1) = sprintf('%.0f', J); %#ok<AGROW>
        if extra
            cells(end+1) = sprintf('%.0f', 100 * stat(R, m, 'Busy')); %#ok<AGROW>
            cells(end+1) = sprintf('%.3f', mean(R.Messages(m) ./ R.RHCPs(m), 'omitnan')); %#ok<AGROW>
        end
        lbl = regexprep(replace(rows{q, 1}, ["0.5", "1", "2", "5"], [" Half ", " One ", " Two ", " Five "]), '[^A-Za-z ]', '');
        mac(end+1, 1) = macro(key + "J" + camel(lbl) + camel(sc), J, '%.0f'); %#ok<AGROW>
    end
    fprintf(fid, '%s & %s \\\\ \\hline\n', rows{q, 1}, strjoin(cells, ' & '));
end
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
end

