function P = paperProfiles()
% Paper profiles for the GUI's Paper profile dropdown (MainUI.setPaperProfile): each shows only
% the components, speed profiles and scenarios that one paper uses, so its setups are quick to
% find. "Full" (the default) shows everything. A field left empty shows everything of that
% kind; a scenario entry ending in * matches every scenario name that starts with the rest.
% Profiles only filter the dropdowns: the registry, layouts and runTrial ignore them, so no
% result depends on a profile. extensionTest checks that every listed name exists.
P = [
    profile("Full", "every component and scenario")
    profile("Simulator paper", "the components and scenarios of the simulator paper", ...
        policy=["Random Walk", "ED-RHC", "ED-ORHC-SO", "ED-ORHC-FO-3", "Battery-Aware ED-RHC", ...
                "Simple Policy (example)"], ...
        agenttype=["Abstract Agent", "Physical Agent", "Simple Agent (example)"])
    profile("Collaboration paper", "ED-RHC and Collab-ED-RHC with abstract FO-0 agents: JS presets, Collab setups, five maps", ...
        policy=["ED-RHC", "Collab-ED-RHC"], agenttype="Abstract Agent", pathplanner="Dijkstra Corners", ...
        targettype="Uncertainty Target", metric="Average Uncertainty J(t)", speedprofile="FO-0", ...
        scenario=["JS: *", "Collab: *", "Lab floor (Stevens)", "Office floor", "City patrol", ...
                  "Harbor patrol", "Campus"])
    profile("Energy paper", "energy-aware and battery-aware ED-RHC with SO and FO-3 profiles", ...
        policy=["ED-RHC", "ED-ORHC-SO", "ED-ORHC-FO-3", "Battery-Aware ED-RHC", "Energy-Aware ED-RHC"], ...
        agenttype=["Abstract Agent", "Physical Agent"], targettype="Uncertainty Target", ...
        metric=["Average Uncertainty J(t)", "Minimum SOC"], speedprofile=["SO", "FO-3"], ...
        scenario=["Energy: *", "Lab floor (Stevens)"])
    ];
end

function p = profile(name, description, opts)
arguments
    name (1,1) string
    description (1,1) string
    opts.policy (1,:) string = strings(1, 0)        % ComponentRegistry names of each kind
    opts.agenttype (1,:) string = strings(1, 0)
    opts.pathplanner (1,:) string = strings(1, 0)
    opts.targettype (1,:) string = strings(1, 0)
    opts.metric (1,:) string = strings(1, 0)
    opts.speedprofile (1,:) string = strings(1, 0)  % SpeedProfile.names
    opts.scenario (1,:) string = strings(1, 0)      % scenarioCatalog names
end
p = struct('Name', name, 'Description', description, 'policy', opts.policy, ...
    'agenttype', opts.agenttype, 'pathplanner', opts.pathplanner, 'targettype', opts.targettype, ...
    'metric', opts.metric, 'speedprofile', opts.speedprofile, 'scenario', opts.scenario);
end
